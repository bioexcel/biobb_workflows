# ---------------- per-workflow runtime cuts (TEST_SETTINGS of nextflow_wf_generator.py) ----------------
adjust_runtime() {
  # $1 = copy of nextflow.config
  "${SED_INPLACE[@]}" 's/nsteps: [0-9]+/nsteps: 50/g' "$1"
}
